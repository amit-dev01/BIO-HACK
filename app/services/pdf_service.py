CONF_AMBER = colors.HexColor("#E65100")  # 60-79
CONF_RED = colors.HexColor("#C62828")    # < 60


class NumberedCanvas(canvas.Canvas):
    """Custom canvas that tracks total pages to draw a dynamic, centered footer on every page."""

    def __init__(self, *args: Any, **kwargs: Any) -> None:
        super().__init__(*args, **kwargs)
        self._saved_page_states: List[Dict[str, Any]] = []
        self.report_id: str = "N/A"

    def showPage(self) -> None:
        self._saved_page_states.append(dict(self.__dict__))
        self._startPage()

    def save(self) -> None:
        num_pages = len(self._saved_page_states)
        for state in self._saved_page_states:
            self.__dict__.update(state)
            self.draw_footer(num_pages)
            super().showPage()
        super().save()

    def draw_footer(self, page_count: int) -> None:
        self.saveState()
        self.setFont("Helvetica", 7)
        self.setFillColor(TEXT_GRAY)
        footer_text = f"Generated by CanopyAI  •  Report ID: {self.report_id}  •  Page {self._pageNumber} of {page_count}"
        page_width, _ = A4
        self.drawCentredString(page_width / 2.0, 1.2 * cm, footer_text)
        self.restoreState()


def _format_confidence_score(score: Any) -> Tuple[str, colors.Color]:
    """Return formatted confidence score string and its alert color."""
    if score is None:
        return "N/A", TEXT_GRAY
    try:
        val = float(score)
        if val <= 1.0:
            val = val * 100.0
        int_score = int(round(val))
        if int_score >= 80:
            return f"{int_score}", CONF_GREEN
        elif int_score >= 60:
            return f"{int_score}", CONF_AMBER
        else:
            return f"{int_score}", CONF_RED
    except (ValueError, TypeError):
        return "N/A", TEXT_GRAY


def _generate_ndvi_chart(ndvi_data: Any) -> Optional[BytesIO]:
    """Generate a Matplotlib line chart for vegetation trends in-memory.

    Returns BytesIO buffer containing PNG bytes, or None if data is missing or invalid.
    """
    if not ndvi_data:
        return None

    # Parse quarterly trend data points
    labels: List[str] = []
    values: List[float] = []

    if isinstance(ndvi_data, (list, tuple)):
        # List of numbers or dicts
        for idx, item in enumerate(ndvi_data):
            if isinstance(item, (int, float)):
                labels.append(f"Q{idx + 1}")
                values.append(float(item))
            elif isinstance(item, dict):
                label = item.get("quarter") or item.get("date") or item.get("label") or f"Q{idx + 1}"
                val = item.get("ndvi") or item.get("value") or item.get("y")
                if val is not None:
                    try:
                        labels.append(str(label))
                        values.append(float(val))
                    except (ValueError, TypeError):
                        continue
            elif isinstance(item, (list, tuple)) and len(item) >= 2:
                try:
                    labels.append(str(item[0]))
                    values.append(float(item[1]))
                except (ValueError, TypeError):
                    continue
    elif isinstance(ndvi_data, dict):
        for k, v in ndvi_data.items():
            try:
                values.append(float(v))
                labels.append(str(k))
            except (ValueError, TypeError):
                continue

    if not values:
        return None

    try:
        # Create figure: 8 inches wide, 3 inches tall, DPI 150
        fig, ax = plt.subplots(figsize=(8, 3), dpi=150)

        x_indices = list(range(len(values)))
        ax.plot(x_indices, values, color="#1B5E20", linewidth=2.2, marker="o", markersize=4.5)
        ax.fill_between(x_indices, values, color="#A5D6A7", alpha=0.35)

        ax.set_title("Vegetation Health Trend (NDVI)", fontsize=11, fontweight="bold", pad=10, color="#1B5E20")
        ax.set_ylim(0.0, 1.0)
        ax.set_ylabel("NDVI", fontsize=9, fontweight="bold")
        ax.set_xticks(x_indices)
        ax.set_xticklabels(labels, rotation=45, ha="right", fontsize=8)
        ax.grid(True, color="#E0E0E0", linestyle="--", linewidth=0.7, alpha=0.7)

        # Style spines
        for spine in ["top", "right"]:
            ax.spines[spine].set_visible(False)
        ax.spines["left"].set_color("#BDBDBD")
        ax.spines["bottom"].set_color("#BDBDBD")

        plt.tight_layout()

        img_buffer = BytesIO()
        fig.savefig(img_buffer, format="png", dpi=150, bbox_inches="tight")
        plt.close(fig)
        img_buffer.seek(0)
        return img_buffer

    except Exception as e:
        logger.warning("Failed to render Matplotlib NDVI chart: %s", str(e), exc_info=True)
        try:
            plt.close("all")
        except Exception:
            pass
        return None


class PDFService:
    """PDF generation service converting forest carbon analyses into downloadable reports."""

    def __init__(self) -> None:
        pass

    def generate_report(self, analysis_data: Union[Dict[str, Any], Any]) -> bytes:
        """Build a complete, professional multi-section PDF report from analysis dictionary."""
        # Normalize analysis_data to a dictionary
        if hasattr(analysis_data, "model_dump"):
            data: Dict[str, Any] = analysis_data.model_dump(mode="json")
        elif isinstance(analysis_data, dict):
            # Check if wrapped in full_response
            data = analysis_data.get("full_response", analysis_data)
        else:
            data = dict(analysis_data)

        buffer = BytesIO()
        # Page size A4, 2 cm margins
        doc = SimpleDocTemplate(
            buffer,
            pagesize=A4,
            leftMargin=2 * cm,
            rightMargin=2 * cm,
            topMargin=2 * cm,
            bottomMargin=2 * cm,
        )

        styles = getSampleStyleSheet()

        # Custom typography styles adhering to specs
        title_style = ParagraphStyle(
            name="ReportTitle",
            fontName="Helvetica-Bold",
            fontSize=22,
            leading=26,
            textColor=PRIMARY_GREEN,
            spaceAfter=3,
        )

        subtitle_style = ParagraphStyle(
            name="ReportSubtitle",
            fontName="Helvetica-Bold",
            fontSize=14,
            leading=18,
            textColor=TEXT_DARK,
            spaceAfter=8,
        )

        meta_style = ParagraphStyle(
            name="ReportMeta",
            fontName="Helvetica",
            fontSize=9,
            leading=13,
            textColor=TEXT_MUTED,
        )

        section_heading = ParagraphStyle(
            name="SectionHeading",
            fontName="Helvetica-Bold",
            fontSize=14,
            leading=18,
            textColor=PRIMARY_GREEN,
            spaceBefore=14,
            spaceAfter=6,
            keepWithNext=True,
        )

        table_header_style = ParagraphStyle(
            name="TableHeader",
            fontName="Helvetica-Bold",
            fontSize=9,
            leading=12,
            textColor=colors.white,
        )

        table_metric_style = ParagraphStyle(
            name="TableMetric",
            fontName="Helvetica",
            fontSize=9,
            leading=12,
            textColor=TEXT_DARK,
        )

        table_value_style = ParagraphStyle(
            name="TableValue",
            fontName="Courier",
            fontSize=9,
            leading=12,
            textColor=TEXT_DARK,
        )

        methodology_style = ParagraphStyle(
            name="MethodologyText",
            fontName="Helvetica-Oblique",
            fontSize=8,
            leading=11,
            textColor=TEXT_MUTED,
            spaceAfter=6,
        )

        body_style = ParagraphStyle(
            name="ReportBody",
            fontName="Helvetica",
            fontSize=10,
            leading=14,
            textColor=TEXT_DARK,
            spaceAfter=4,
        )

        story: List[Any] = []

        # --- SECTION 1: HEADER ---
        analysis_id = str(data.get("analysis_id") or "N/A")
        raw_created = data.get("timestamp") or data.get("created_at")
        report_date_str = "N/A"
        if raw_created:
            try:
                if isinstance(raw_created, str):
                    dt_created = datetime.fromisoformat(raw_created.replace("Z", "+00:00"))
                elif isinstance(raw_created, datetime):
                    dt_created = raw_created
                else:
                    dt_created = datetime.now(timezone.utc)
                report_date_str = dt_created.strftime("%Y-%m-%d")
            except Exception:
                report_date_str = str(raw_created)[:10]

        now_str = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")

        data_mode_raw = str(data.get("data_mode") or "mock").lower()
        is_satellite = data_mode_raw == "satellite"
        data_mode_label = "Satellite Data" if is_satellite else "Mock Data"

        story.append(Paragraph("CanopyAI Forest Carbon Assessment", title_style))
        story.append(Paragraph("Pre-Screening Report", subtitle_style))

        # Header metadata block
        header_meta = [
            [
                Paragraph(f"<b>Analysis ID:</b> <font name='Courier'>{analysis_id}</font>", meta_style),
                Paragraph(f"<b>Data Mode:</b> <b>{data_mode_label}</b>", meta_style),
            ],
            [
                Paragraph(f"<b>Report Date:</b> {report_date_str}", meta_style),
                Paragraph(f"<b>Generation Date:</b> {now_str}", meta_style),
            ],
        ]
        t_meta = Table(header_meta, colWidths=[240, 240])
        t_meta.setStyle(
            TableStyle(
                [
                    ("VALIGN", (0, 0), (-1, -1), "TOP"),
                    ("TOPPADDING", (0, 0), (-1, -1), 1),
                    ("BOTTOMPADDING", (0, 0), (-1, -1), 2),
                    ("LEFTPADDING", (0, 0), (-1, -1), 0),
                    ("RIGHTPADDING", (0, 0), (-1, -1), 0),
                ]
            )
        )
        story.append(t_meta)
        story.append(Spacer(1, 4))
        # Horizontal divider line below header (RGB 27, 94, 32)
        story.append(
            HRFlowable(
                width="100%",
                thickness=1.5,
                color=PRIMARY_GREEN,
                spaceBefore=4,
                spaceAfter=10,
            )
        )

        # --- SECTION 2: KEY METRICS SUMMARY (2x2 Grid) ---
        total_co2e_val = data.get("total_co2e")
        total_co2e_str = f"{float(total_co2e_val):,.2f}" if total_co2e_val is not None else "N/A"

        area_ha_val = data.get("area_ha")
        area_ha_str = f"{float(area_ha_val):,.2f}" if area_ha_val is not None else "N/A"

        canopy_val = data.get("canopy_cover_pct")
        canopy_str = f"{float(canopy_val):.1f}" if canopy_val is not None else "N/A"

        conf_val = data.get("confidence_score")
        conf_str, conf_color = _format_confidence_score(conf_val)

        def make_metric_box(label: str, value: str, unit: str, val_color: colors.Color = PRIMARY_GREEN) -> Table:
            content = [
                [Paragraph(label.upper(), ParagraphStyle(name="BLabel", fontName="Helvetica-Bold", fontSize=8, leading=10, textColor=TEXT_MUTED))],
                [Paragraph(value, ParagraphStyle(name="BVal", fontName="Courier-Bold", fontSize=18, leading=22, textColor=val_color))],
                [Paragraph(unit, ParagraphStyle(name="BUnit", fontName="Helvetica", fontSize=8, leading=10, textColor=TEXT_GRAY))],
            ]
            box_table = Table(content, colWidths=[234])
            box_table.setStyle(
                TableStyle(
                    [
                        ("BACKGROUND", (0, 0), (-1, -1), LIGHT_GREEN_BG),
                        ("BOX", (0, 0), (-1, -1), 1, BORDER_GREEN),
                        ("TOPPADDING", (0, 0), (-1, -1), 6),
                        ("BOTTOMPADDING", (0, 0), (-1, -1), 6),
                        ("LEFTPADDING", (0, 0), (-1, -1), 10),
                        ("RIGHTPADDING", (0, 0), (-1, -1), 10),
                        ("ALIGN", (0, 0), (-1, -1), "LEFT"),
                    ]
                )
            )
            return box_table

        box1 = make_metric_box("Total Carbon Stock", total_co2e_str, "tCO₂e", PRIMARY_GREEN)
        box2 = make_metric_box("Forest Area", area_ha_str, "hectares", PRIMARY_GREEN)
        box3 = make_metric_box("Canopy Cover", canopy_str, "%", PRIMARY_GREEN)
        box4 = make_metric_box("Confidence Score", conf_str, "/100", conf_color)

        grid_data = [
            [box1, box2],
            [box3, box4],
        ]
        grid_table = Table(grid_data, colWidths=[240, 240])
        grid_table.setStyle(
            TableStyle(
                [
                    ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
                    ("TOPPADDING", (0, 0), (-1, -1), 3),
                    ("BOTTOMPADDING", (0, 0), (-1, -1), 3),
                    ("LEFTPADDING", (0, 0), (-1, -1), 0),
                    ("RIGHTPADDING", (0, 0), (-1, -1), 0),
                ]
            )
        )
        story.append(grid_table)
        story.append(Spacer(1, 10))

        # --- SECTION 3: FOREST CHARACTERISTICS TABLE ---
        story.append(Paragraph("Forest Characteristics", section_heading))

        def fmt_val(v: Any, unit: str = "", fmt: str = ".2f") -> str:
            if v is None:
                return "N/A"
            try:
                numeric_val = float(v)
                s = f"{numeric_val:{fmt}}"
                return f"{s} {unit}".strip() if unit else s
            except (ValueError, TypeError):
                return str(v)

        forest_rows = [
            [Paragraph("Metric", table_header_style), Paragraph("Value", table_header_style)],
            [Paragraph("Forest Type", table_metric_style), Paragraph(str(data.get("forest_type") or "N/A"), table_value_style)],
            [Paragraph("Ecoregion", table_metric_style), Paragraph(str(data.get("ecoregion") or "N/A"), table_value_style)],
            [Paragraph("Mean Canopy Height", table_metric_style), Paragraph(fmt_val(data.get("mean_canopy_height_m"), "m", ".1f"), table_value_style)],
            [Paragraph("Above-Ground Biomass", table_metric_style), Paragraph(fmt_val(data.get("agb_t_per_ha"), "t/ha", ",.2f"), table_value_style)],
            [Paragraph("Below-Ground Biomass", table_metric_style), Paragraph(fmt_val(data.get("bgb_t_per_ha"), "t/ha", ",.2f"), table_value_style)],
            [Paragraph("Total Biomass", table_metric_style), Paragraph(fmt_val(data.get("total_biomass_t_per_ha"), "t/ha", ",.2f"), table_value_style)],
            [Paragraph("Carbon Fraction", table_metric_style), Paragraph(fmt_val(data.get("carbon_fraction"), "", ".3f"), table_value_style)],
        ]
        t_forest = Table(forest_rows, colWidths=[200, 280])
        t_forest_style = [
            ("BACKGROUND", (0, 0), (-1, 0), PRIMARY_GREEN),
            ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
            ("GRID", (0, 0), (-1, -1), 0.5, BORDER_GRAY),
            ("TOPPADDING", (0, 0), (-1, -1), 3),
            ("BOTTOMPADDING", (0, 0), (-1, -1), 3),
            ("LEFTPADDING", (0, 0), (-1, -1), 8),
            ("RIGHTPADDING", (0, 0), (-1, -1), 8),
        ]
        for r_idx in range(1, len(forest_rows)):
            bg = LIGHT_GRAY if r_idx % 2 == 1 else colors.white
            t_forest_style.append(("BACKGROUND", (0, r_idx), (-1, r_idx), bg))
        t_forest.setStyle(TableStyle(t_forest_style))
        story.append(t_forest)
        story.append(Spacer(1, 10))

        # --- SECTION 4: CARBON STOCK TABLE ---
        story.append(Paragraph("Carbon Stock Metrics", section_heading))

        carbon_rows = [
            [Paragraph("Metric", table_header_style), Paragraph("Value", table_header_style)],
            [Paragraph("Carbon Stock", table_metric_style), Paragraph(fmt_val(data.get("carbon_t_per_ha"), "tC/ha", ",.2f"), table_value_style)],
            [Paragraph("CO₂ Equivalent", table_metric_style), Paragraph(fmt_val(data.get("co2e_t_per_ha"), "tCO₂e/ha", ",.2f"), table_value_style)],
            [Paragraph("Total CO₂e", table_metric_style), Paragraph(fmt_val(data.get("total_co2e"), "tCO₂e", ",.2f"), table_value_style)],
            [Paragraph("Annual Sequestration", table_metric_style), Paragraph(fmt_val(data.get("annual_sequestration_tco2e"), "tCO₂e/yr", ",.2f"), table_value_style)],
        ]
        t_carbon = Table(carbon_rows, colWidths=[200, 280])
        t_carbon_style = [
            ("BACKGROUND", (0, 0), (-1, 0), PRIMARY_GREEN),
            ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
            ("GRID", (0, 0), (-1, -1), 0.5, BORDER_GRAY),
            ("TOPPADDING", (0, 0), (-1, -1), 3),
            ("BOTTOMPADDING", (0, 0), (-1, -1), 3),
            ("LEFTPADDING", (0, 0), (-1, -1), 8),
            ("RIGHTPADDING", (0, 0), (-1, -1), 8),
        ]
        for r_idx in range(1, len(carbon_rows)):
            bg = LIGHT_GRAY if r_idx % 2 == 1 else colors.white
            t_carbon_style.append(("BACKGROUND", (0, r_idx), (-1, r_idx), bg))
        t_carbon.setStyle(TableStyle(t_carbon_style))
        story.append(t_carbon)
        story.append(Spacer(1, 10))

        # --- SECTION 5: VEGETATION TREND CHART ---
        story.append(Paragraph("Vegetation Trend", section_heading))
        chart_buffer = _generate_ndvi_chart(data.get("ndvi_trend"))
        if chart_buffer is not None:
            # Printable width is 480 points; 8:3 ratio gives height 180 points
            story.append(Image(chart_buffer, width=480, height=180))
        else:
            # Fallback text when data is missing, empty, or chart fails
            story.append(Paragraph("Vegetation trend data unavailable.", ParagraphStyle(name="NoChart", fontName="Helvetica", fontSize=9, leading=13, textColor=TEXT_MUTED)))
        story.append(Spacer(1, 10))

        # --- SECTION 6: DATA SOURCES ---
        story.append(Paragraph("Data Sources", section_heading))
        data_sources = data.get("data_sources") or []
        if isinstance(data_sources, list) and len(data_sources) > 0:
            for ds in data_sources:
                story.append(Paragraph(f"&bull;&nbsp;&nbsp;{ds}", body_style))
        else:
            story.append(Paragraph("No specific data sources listed.", body_style))

        # Mode note
        if not is_satellite:
            mode_note = (
                "This report is based on simulated data for demonstration purposes. "
                "Results do not represent actual satellite measurements."
            )
        else:
            mode_note = "This report is based on satellite remote sensing observations from the listed sources."

        story.append(Spacer(1, 4))
        story.append(Paragraph(f"<b>Notice:</b> {mode_note}", ParagraphStyle(name="ModeNote", fontName="Helvetica-Bold", fontSize=9, leading=12, textColor=PRIMARY_GREEN)))
        story.append(Spacer(1, 10))

        # --- SECTION 7: METHODOLOGY NOTE ---
        story.append(Paragraph("Methodology & Disclaimers", section_heading))
        p1 = (
            "This estimate is based on satellite remote sensing data. Biomass estimates are derived "
            "from spaceborne LiDAR observations and optical satellite imagery. Carbon calculations "
            "follow IPCC Tier 1 guidelines using a carbon fraction of 0.47 and a CO₂ conversion factor "
            "of 3.67."
        )
        p2 = (
            "This is a pre-screening estimate. It does not constitute formal carbon credit verification. "
            "Actual carbon stocks may vary due to local ecological conditions, species composition, "
            "soil carbon, and measurement uncertainty."
        )
        p3 = (
            "For formal carbon credit issuance, a full field-based MRV (Measurement, Reporting, "
            "and Verification) assessment by an accredited verification body is required."
        )
        story.append(Paragraph(p1, methodology_style))
        story.append(Paragraph(p2, methodology_style))
        story.append(Paragraph(p3, methodology_style))

        # --- SECTION 8: FOOTER (via NumberedCanvas) ---
        class CustomNumberedCanvas(NumberedCanvas):
            pass

        CustomNumberedCanvas.report_id = analysis_id

        doc.build(story, canvasmaker=CustomNumberedCanvas)
        pdf_bytes = buffer.getvalue()
        buffer.close()

        return pdf_bytes

    def generate_report_by_id(self, analysis_id: str) -> bytes:
        """Fetch analysis by ID and generate its complete PDF report bytes."""
        analysis = database_service.get_analysis_by_id(analysis_id)
        if not analysis:
            raise AnalysisNotFoundError(analysis_id=analysis_id)

        # Convert to dictionary if needed
        if hasattr(analysis, "model_dump"):
            analysis_dict = analysis.model_dump(mode="json")
        elif isinstance(analysis, dict):
            analysis_dict = analysis.get("full_response", analysis)
        else:
            analysis_dict = dict(analysis)

        return self.generate_report(analysis_dict)


# Global service instance
pdf_service = PDFService()


# Public functional interface
def generate_pdf_report(analysis_data: Dict[str, Any]) -> bytes:
    """Generate raw PDF report bytes from analysis dictionary. Public function interface."""
    return pdf_service.generate_report(analysis_data)
